    public function run()
    {
        $now = date('Y-m-d H:i:s');

        foreach ($this->lines() as $line) {
            $stations = $line['stations'];
            $payload = json_encode($stations, JSON_UNESCAPED_UNICODE);
            $data = array(
                'name' => $line['name'],
                'type' => $line['type'],
                'rarity' => $line['rarity'],
                'color' => $line['color'],
                'district' => $line['district'],
                'price_ap' => $line['price_ap'],
                'reward_ap' => $line['reward_ap'],
                'distance_km' => $line['distance_km'],
                'first_bus' => $line['first_bus'],
                'last_bus' => $line['last_bus'],
                'station_count' => count($stations),
                'stations' => $payload,
                'description' => $line['description'],
                'is_free' => $line['is_free'],
                'sort_order' => $line['sort_order'],
                'status' => 1,
                'updated_at' => $now,
            );

            $exists = DB::table('point_bus_catalog')->where('code', $line['code'])->first();
            if ($exists) {
                DB::table('point_bus_catalog')->where('id', $exists->id)->update($data);
            } else {
                $data['code'] = $line['code'];
                $data['created_at'] = $now;
                DB::table('point_bus_catalog')->insert($data);
            }
        }

        foreach ($this->achievements() as $achievement) {
            $data = array(
                'name' => $achievement['name'],
                'description' => $achievement['description'],
                'condition_type' => $achievement['condition_type'],
                'condition_payload' => json_encode($achievement['condition_payload'], JSON_UNESCAPED_UNICODE),
                'reward_ap' => $achievement['reward_ap'],
                'badge_icon' => $achievement['badge_icon'],
                'sort_order' => $achievement['sort_order'],
                'status' => 1,
                'updated_at' => $now,
            );

            $exists = DB::table('point_bus_achievements')->where('code', $achievement['code'])->first();
            if ($exists) {
                DB::table('point_bus_achievements')->where('id', $exists->id)->update($data);
            } else {
                $data['code'] = $achievement['code'];
                $data['created_at'] = $now;
                DB::table('point_bus_achievements')->insert($data);
            }
        }
    }

